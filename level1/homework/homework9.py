# if-else პირობითი ოპერატორი გამოიყენება პროგრამაში სხვადასხვა სცენარის განსასაზღვრავად.
# პროგრამა ამოწმებს მოცემულ პირობას:
# - თუ პირობა ჭეშმარიტია (True), სრულდება if ბლოკში არსებული კოდი.
# - თუ პირობა მცდარია (False), ავტომატურად ირთვება და სრულდება else ბლოკი.

number = int(input("შემოიტანეთ რიცხვი: "))
if number % 2 == 0:
    print("Number is even")
else:
    print("Number is odd")

